def build_holdout() -> List[Dict[str, Any]]:  # Any: JSON scenario mapping
    out: List[Dict[str, Any]] = []
    for idx, (is_scam, cat, lang, amount, is_new, hour, freq, text) in enumerate(_ROWS, start=1001):
        out.append({
            "id": idx,
            "is_scam": is_scam,
            "category": cat,
            "language": lang,
            "amount": float(amount),
            "is_new_recipient": is_new,
            "transfer_hour": hour,
            "frequency_last_hour": freq,
            "answer_text": text,
            "attack_vector": cat if is_scam else "benign_holdout",
            "split": "holdout",
        })
    return out


